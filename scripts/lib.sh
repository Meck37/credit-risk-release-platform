#!/usr/bin/env bash
# Shared helpers for the deployment scripts. Sourced, never run directly.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# Runtime state lives OUTSIDE the git repo: which image runs where, release records,
# nginx configs, Prometheus targets and backups.
export OPS_HOME="${OPS_HOME:-$HOME/mlops-ops}"
PYTHON="${PYTHON:-python3}"

mkdir -p "$OPS_HOME"/{state,records,nginx,prometheus-targets,backups}

log() { printf '[%s] %s\n' "$(date -u +%H:%M:%S)" "$*"; }
die() { log "ERROR: $*"; exit 1; }

load_env() {  # load_env dev|staging|prod
  local env_file="$REPO_ROOT/deploy/envs/$1.env"
  [[ -f "$env_file" ]] || die "unknown environment '$1'"
  set -a
  # shellcheck source=/dev/null
  source "$env_file"
  set +a
  mkdir -p "$OPS_HOME/nginx/$APP_ENV"
}

compose() {  # compose <env> <docker compose args...>
  local env="$1"; shift
  docker compose -f "$REPO_ROOT/deploy/app/docker-compose.yml" \
    --env-file "$REPO_ROOT/deploy/envs/$env.env" "$@"
}

state_file() { echo "$OPS_HOME/state/$1.json"; }

state_get() {  # state_get <env> <key>  -> prints value or empty
  local f; f="$(state_file "$1")"
  [[ -f "$f" ]] || { echo ""; return; }
  "$PYTHON" -c "import json,sys; print(json.load(open(sys.argv[1])).get(sys.argv[2]) or '')" "$f" "$2"
}

state_set() {  # state_set <env> key=value [key=value ...]
  local f; f="$(state_file "$1")"; shift
  "$PYTHON" - "$f" "$@" <<'PY'
import json, sys, os, datetime
path, pairs = sys.argv[1], sys.argv[2:]
state = json.load(open(path)) if os.path.exists(path) else {}
for pair in pairs:
    key, _, value = pair.partition("=")
    state[key] = value
state["updated_at"] = datetime.datetime.now(datetime.timezone.utc).isoformat()
json.dump(state, open(path, "w"), indent=2)
PY
}

write_nginx() {  # write_nginx <env> stable|split|canary-only
  local env="$1" mode="$2" weight="${CANARY_WEIGHT:-10}" servers
  case "$mode" in
    stable)      servers="    server scoring-${env}-stable:8000;" ;;
    canary-only) servers="    server scoring-${env}-canary:8000;" ;;
    split)       servers="    server scoring-${env}-stable:8000 weight=$((100 - weight));
    server scoring-${env}-canary:8000 weight=${weight};" ;;
    *) die "unknown nginx mode $mode" ;;
  esac
  cat > "$OPS_HOME/nginx/$env/default.conf" <<EOF
# Generated by scripts/lib.sh (mode: $mode) - do not edit by hand.
log_format scoring_json escape=json '{"time":"\$time_iso8601","request_id":"\$request_id",'
  '"status":\$status,"upstream":"\$upstream_addr","duration":\$request_time,"uri":"\$uri"}';

upstream scoring_api {
$servers
}

server {
    listen 8080;
    access_log /var/log/nginx/access.log scoring_json;
    client_max_body_size 64k;

    location / {
        proxy_pass http://scoring_api;
        proxy_set_header X-Request-ID \$request_id;   # same id in nginx and API logs
        proxy_set_header Host \$host;
        proxy_connect_timeout 2s;
        proxy_read_timeout 10s;
    }
}
EOF
}

reload_gateway() {  # reload_gateway <env>  (validate first, so a bad config never goes live)
  docker exec "scoring-$1-gateway" nginx -t -q && docker exec "scoring-$1-gateway" nginx -s reload
}

refresh_targets() { "$PYTHON" "$REPO_ROOT/scripts/refresh_targets.py"; }

record() {  # record key=value ...   -> appends one JSON line to the release log
  "$PYTHON" "$REPO_ROOT/scripts/record_release.py" "$@"
}